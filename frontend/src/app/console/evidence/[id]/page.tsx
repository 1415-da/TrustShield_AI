"use client";

import { ArrowLeft, CalendarClock, Download, FileJson, FileText, Globe, Link2, ShieldCheck, ShieldX, Trash2 } from "lucide-react";
import Link from "next/link";
import { useParams, useRouter } from "next/navigation";
import { useEffect, useState } from "react";

import { Section } from "@/components/console/shell";
import { ActionBadge } from "@/components/trust/badges";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { ConfirmDialog } from "@/components/ui/confirm";
import { Dialog } from "@/components/ui/dialog";
import { Field, Select } from "@/components/ui/field";
import { ErrorState, LoadingRows, Skeleton } from "@/components/ui/states";
import { useToast } from "@/components/ui/toast";
import { useAuth } from "@/hooks/useAuth";
import { useApi } from "@/hooks/useApi";
import { api, ApiError, download } from "@/lib/api";
import { dateTime, shortDate } from "@/lib/format";
import type { AuditEvent, ComplianceReport, VerifyResult } from "@/lib/types";

interface SourcesPage { total: number; page: number; page_size: number; items: AuditEvent[] }

export default function ReportDetailPage() {
  const { id } = useParams<{ id: string }>();
  const { can } = useAuth();
  const router = useRouter();
  const toast = useToast();
  const writable = can("compliance:write");
  const [polling, setPolling] = useState(true);
  const report = useApi<ComplianceReport>(`/compliance/reports/${id}`, polling ? 1500 : undefined);
  const r = report.data;
  useEffect(() => { if (r && r.status !== "GENERATING") setPolling(false); }, [r?.status]); // eslint-disable-line react-hooks/exhaustive-deps
  const [modal, setModal] = useState<null | "export" | "schedule" | "withdraw" | "sources">(null);
  const [cadence, setCadence] = useState("monthly");
  const [verify, setVerify] = useState<VerifyResult | null>(null);
  const [verifying, setVerifying] = useState(false);
  const [page, setPage] = useState(1);
  const sources = useApi<SourcesPage>(modal === "sources" ? `/compliance/evidence/${id}/sources?page=${page}&page_size=25` : null);

  if (report.loading && !r) return <LoadingRows rows={6} />;
  if (report.error || !r) return <ErrorState message={report.error?.message ?? "Report not found"} onRetry={report.reload} />;
  const c = r.content;
  const ready = r.status === "READY" || r.status === "EXPIRED";

  const doExport = async (format: "markdown" | "json" | "html") => {
    try {
      await download(`/compliance/reports/${r.id}/export?format=${format}`, `report-${r.id}.${format === "markdown" ? "md" : format}`);
      toast({ tone: "success", title: "Export ready", body: format === "json" ? "Evidence package downloaded." : `${format.toUpperCase()} report downloaded.` });
    } catch (e) {
      toast({ tone: "error", title: "Export failed", body: e instanceof ApiError ? e.message : undefined });
    }
  };
  const runVerify = async () => {
    setVerifying(true);
    try { setVerify(await api<VerifyResult>(`/compliance/reports/${r.id}/verify`)); } finally { setVerifying(false); }
  };

  return (
    <>
      <Link href="/console/evidence" className="mb-4 inline-flex items-center gap-1.5 text-[13px] text-ink-500 hover:text-ink"><ArrowLeft className="h-3.5 w-3.5" />Evidence Center</Link>
      <div className="mb-6 flex flex-col gap-4 border-b border-hair pb-6 lg:flex-row lg:items-end lg:justify-between">
        <div className="max-w-3xl">
          <p className="eyebrow mb-2">Report {r.id} · version {r.version}{r.deleted_at ? " · withdrawn" : ""}</p>
          <h1 className="text-[32px] leading-[1.1] sm:text-[38px]">{c?.title ?? r.title}</h1>
          <p className="mt-2 text-[14px] text-ink-700">Evidence period {shortDate(r.period_start)} – {shortDate(r.period_end)} · generated by {r.generated_by_email}</p>
        </div>
        {ready && !r.deleted_at && (
          <div className="flex flex-wrap gap-2">
            <Button variant="ghost" onClick={() => setModal("sources")}><Link2 className="h-4 w-4" />Source records</Button>
            {writable && <Button variant="secondary" onClick={() => setModal("schedule")}><CalendarClock className="h-4 w-4" />Schedule</Button>}
            <Button onClick={() => setModal("export")} data-testid="export-report"><Download className="h-4 w-4" />Export report</Button>
            {writable && <Button variant="ghost" aria-label="Withdraw report" onClick={() => setModal("withdraw")}><Trash2 className="h-4 w-4" /></Button>}
          </div>
        )}
      </div>

      {r.status === "GENERATING" && (
        <div className="space-y-4" role="status"><p className="text-[14px] text-ink-700">Compiling evidence from audit records…</p><Skeleton className="h-28" /><Skeleton className="h-64" /></div>
      )}
      {r.status === "FAILED" && <ErrorState message={`Report generation failed: ${r.error ?? "unknown error"}`} />}

      {c && (
        <div className="grid gap-6 xl:grid-cols-[1fr_340px]">
          <article className="space-y-6" data-testid="report-preview">
            <Section title="Summary">
              <ul className="space-y-2 text-[14.5px] leading-relaxed">{c.summary.map((s) => <li key={s} className="flex gap-2.5"><span aria-hidden className="mt-[10px] h-1 w-1 shrink-0 rounded-full bg-forest" />{s}</li>)}</ul>
              <dl className="mt-6 grid grid-cols-2 gap-x-6 gap-y-5 border-t border-hair pt-5 sm:grid-cols-4">
                {c.metrics.map((m) => (
                  <div key={m.label} className="border-l border-forest/30 pl-3" title={m.hint}>
                    <dt className="text-[12px] text-ink-500">{m.label}</dt>
                    <dd className="num mt-1 font-serif text-[28px] leading-none text-forest">{m.value}</dd>
                  </div>
                ))}
              </dl>
            </Section>
            {c.sections.map((s) => (
              <Section key={s.title} title={s.title} description={s.description || undefined}>
                {!s.rows.length ? <p className="text-[13px] text-ink-500">{s.empty}</p> : (
                  <div className="overflow-x-auto">
                    <table className="w-full text-left text-[13px]">
                      <thead className="border-b border-hair text-[12px] text-ink-500"><tr>{s.columns.map((col) => <th key={col} className="py-2 pr-4 font-medium">{col}</th>)}</tr></thead>
                      <tbody>{s.rows.map((row, i) => <tr key={i} className="border-b border-hair align-top last:border-0">{row.map((v, j) => <td key={j} className={j > 0 && typeof v === "number" ? "num py-2 pr-4" : "py-2 pr-4"}>{v}</td>)}</tr>)}</tbody>
                    </table>
                  </div>
                )}
              </Section>
            ))}
            <p className="text-[12px] text-ink-500">{c.evidence.statement}</p>
          </article>

          <aside className="space-y-6 xl:sticky xl:top-6 xl:self-start" aria-label="Report integrity">
            <Section title="Evidence integrity">
              <dl className="space-y-2.5 text-[13px]" data-testid="integrity-panel">
                {[["Status", <ActionBadge key="s" action={r.status} />], ["Report ID", `${r.id} · v${r.version}`], ["Generated", dateTime(r.completed_at ?? r.created_at)],
                  ["Generated by", r.generated_by_email], ["Evidence period", `${shortDate(r.period_start)} – ${shortDate(r.period_end)}`],
                  ["Included records", `${r.source_record_count} audit records`], ["Expires", r.expires_at ? shortDate(r.expires_at) : "No expiry"]].map(([k, v]) => (
                  <div key={String(k)} className="flex items-start justify-between gap-3 border-b border-hair pb-2 last:border-0"><dt className="text-ink-500">{k}</dt><dd className="text-right">{v}</dd></div>
                ))}
                <div><dt className="text-ink-500">Content SHA-256</dt><dd className="mt-1 break-all rounded-lg bg-ink px-2.5 py-2 font-mono text-[11px] text-cream">{r.content_hash}</dd></div>
              </dl>
              <Button variant="secondary" className="mt-4 w-full" onClick={() => void runVerify()} loading={verifying} data-testid="verify-report"><ShieldCheck className="h-4 w-4" />Verify integrity</Button>
              {verify && (
                <p className={`mt-3 flex items-start gap-2 rounded-xl px-3 py-2.5 text-[12.5px] ${verify.reproducible ? "bg-sage-100 text-sage-700" : "bg-crimson-100 text-crimson-700"}`} data-testid="verify-result">
                  {verify.reproducible ? <ShieldCheck className="mt-0.5 h-4 w-4 shrink-0" /> : <ShieldX className="mt-0.5 h-4 w-4 shrink-0" />}
                  {verify.reproducible ? "Verified — regenerating from the audit records produces an identical report." : "Mismatch — the regenerated report differs from the stored evidence."}
                </p>
              )}
            </Section>
          </aside>
        </div>
      )}

      <Dialog open={modal === "export"} onClose={() => setModal(null)} title="Export report" description="Exports include the integrity block and the content hash.">
        <div className="space-y-2">
          {([["html", Globe, "Formatted report (HTML)", "Self-contained, print-ready page for auditors and leadership."],
            ["markdown", FileText, "Markdown", "Paste into a wiki, ticket, or pull request."],
            ["json", FileJson, "Evidence package (JSON)", "Structured content, integrity block, and every source audit-record ID."]] as const).map(([fmt, Icon, label, desc]) => (
            <button key={fmt} onClick={() => void doExport(fmt)} className="flex w-full items-start gap-3 rounded-2xl border border-hair bg-white/50 px-4 py-3 text-left transition hover:border-forest/40" data-testid={`export-${fmt}`}>
              <Icon className="mt-0.5 h-5 w-5 text-forest" /><span><span className="block font-medium">{label}</span><span className="block text-[12.5px] text-ink-500">{desc}</span></span>
            </button>
          ))}
        </div>
      </Dialog>
      <ConfirmDialog open={modal === "schedule"} onClose={() => setModal(null)} title="Schedule this report"
        description="TrustShield regenerates this report with the same scope on a schedule. Each run is a new, immutable evidence record."
        confirmLabel="Create schedule" onConfirm={async () => {
          await api(`/compliance/reports/${r.id}/schedule`, { method: "POST", body: { cadence, retention_days: 365 } });
          toast({ tone: "success", title: "Report scheduled", body: `Runs ${cadence}.` });
        }}>
        <Field label="Cadence" htmlFor="cadence"><Select id="cadence" value={cadence} onChange={(e) => setCadence(e.target.value)}><option value="weekly">Weekly</option><option value="monthly">Monthly</option></Select></Field>
      </ConfirmDialog>
      <ConfirmDialog open={modal === "withdraw"} onClose={() => setModal(null)} title="Withdraw this report?" tone="danger"
        description="It disappears from the library. The evidence record itself is retained and the withdrawal is audited." confirmLabel="Withdraw"
        onConfirm={async () => { await api(`/compliance/reports/${r.id}`, { method: "DELETE" }); toast({ tone: "success", title: "Report withdrawn" }); router.replace("/console/evidence"); }} />
      <Dialog open={modal === "sources"} onClose={() => setModal(null)} title="Source records" description={`The ${r.source_record_count} audit records this report was built from.`} side>
        {!sources.data ? <LoadingRows rows={6} /> : (
          <div className="space-y-2" data-testid="evidence-sources">
            {sources.data.items.map((e) => (
              <div key={e.id} className="rounded-xl border border-hair bg-white/50 px-3 py-2 text-[12.5px]">
                <div className="flex flex-wrap items-center gap-2"><span className="font-mono text-[11.5px] text-ink-500">#{e.id}</span><span className="font-mono">{e.event_type}</span>
                  {e.final_action && <ActionBadge action={e.final_action} />}<span className="ml-auto text-ink-500">{dateTime(e.created_at)}</span></div>
                <p className="mt-0.5 text-ink-500">{e.actor_email ?? "system"}{e.request_id ? ` · req ${e.request_id.slice(0, 10)}` : ""}</p>
              </div>
            ))}
            <div className="flex items-center justify-between pt-2 text-[12.5px] text-ink-500">
              <Badge>Page {sources.data.page} of {Math.max(1, Math.ceil(sources.data.total / sources.data.page_size))}</Badge>
              <span className="flex gap-2">
                <Button size="sm" variant="ghost" disabled={page <= 1} onClick={() => setPage(page - 1)}>Previous</Button>
                <Button size="sm" variant="ghost" disabled={page * sources.data.page_size >= sources.data.total} onClick={() => setPage(page + 1)}>Next</Button>
              </span>
            </div>
            <Link href="/console/audit" className="link text-[12.5px]">Open the full audit log</Link>
          </div>
        )}
      </Dialog>
    </>
  );
}
